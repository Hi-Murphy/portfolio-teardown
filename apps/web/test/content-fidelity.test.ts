const projectJsonBySlug = new Map<string, { meta: { name: string } }>(
  rows.map(({ slug, jsonPath }) => [
    slug,
    JSON.parse(readFileSync(jsonPath, 'utf8')) as { meta: { name: string } },
  ]),
);

describe.each(rows)('$slug content fidelity', ({ slug, jsonPath, source, project, sourcePath }) => {
  const bytes = readFileSync(jsonPath);
  const json: unknown = JSON.parse(bytes.toString('utf8'));

  test('(a) generated module is strictly equal to the canonical JSON', () => {
    expect(source).toStrictEqual(json);
  });

  test('(b) parsed module is strictly equal to the canonical JSON parsed project', () => {
    expect(project).toStrictEqual(parseProject(json, { registry: SITE_REGISTRY }));
  });

  test('(c) content:convert --check exits 0', () => {
    const result = spawnSync(process.execPath, [CONVERTER_PATH, '--check'], {
      cwd: APP_WEB_ROOT,
      encoding: 'utf8',
    });

    expect(result.status, result.stderr || result.stdout).toBe(0);
  });

  test('(d) generated header records the canonical JSON sha256', () => {
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const expectedHeader = `/* Generated by apps/web/scripts/convert-content.ts from .specify/content/${slug}.json (sha256 ${sha256}). Do not edit; run pnpm --filter web content:convert. */`;
    const firstLine = readFileSync(sourcePath, 'utf8').split('\n', 1)[0];

    expect(firstLine).toBe(expectedHeader);
  });

  test('(e) negative control: a mutated canonical copy is not strictly equal', () => {
    const mutated = structuredClone(json) as { meta: { tagline: string } };
    mutated.meta.tagline = `${mutated.meta.tagline} (mutated)`;

    expect(source).not.toStrictEqual(mutated);
  });

  test('(e2) negative control: a mutated nested copy is not strictly equal', () => {
    const mutated = structuredClone(json) as {
      layers: Array<{ components: Array<{ summary: string }> }>;
    };
    const lastLayer = mutated.layers.at(-1)!;
    const firstComponent = lastLayer.components[0]!;
    firstComponent.summary = `${firstComponent.summary} (mutated)`;

    expect(source).not.toStrictEqual(mutated);
  });
});

describe.each(relationshipRows)(
  '$slug relationship fidelity',
  ({ slug, jsonPath, source, sourcePath }) => {
    const bytes = readFileSync(jsonPath);
    const json: unknown = JSON.parse(bytes.toString('utf8'));

    test('(a) generated relationship module is strictly equal to the canonical JSON', () => {
      expect(source).toStrictEqual(json);
    });

    test('(c) content:convert --check exits 0', () => {
      const result = spawnSync(process.execPath, [CONVERTER_PATH, '--check'], {
        cwd: APP_WEB_ROOT,
        encoding: 'utf8',
      });

      expect(result.status, result.stderr || result.stdout).toBe(0);
    });

    test('(d) generated header records the canonical relationship JSON sha256', () => {
      const sha256 = createHash('sha256').update(bytes).digest('hex');
      const expectedHeader = `/* Generated by apps/web/scripts/convert-content.ts from .specify/content/relationships/${slug}.json (sha256 ${sha256}). Do not edit; run pnpm --filter web content:convert. */`;
      const firstLine = readFileSync(sourcePath, 'utf8').split('\n', 1)[0];

      expect(firstLine).toBe(expectedHeader);
    });

    test('(e) negative control: a mutated relationship note is not strictly equal', () => {
      const mutated = structuredClone(json) as { relationships: Array<{ note: string }> };
      mutated.relationships[0]!.note = `${mutated.relationships[0]!.note} (mutated)`;

      expect(source).not.toStrictEqual(mutated);
    });

    test('(f) connections match the canonical relationship JSON', () => {
      const canonical = json as {
        relationships: readonly { to: string; kind: string; note: string }[];
      };
      const expected = canonical.relationships.map(({ to, kind, note }) => {
        const target = projectJsonBySlug.get(to);

        if (target === undefined) throw new Error(`Missing project JSON for "${to}".`);

        return { slug: to, name: target.meta.name, kind, note };
      });

      expect(connectionsFor(slug)).toStrictEqual(expected);
    });
  },
);

test('completeness: content files, fidelity rows and converter entries agree', () => {
  const contentSlugs = readdirSync(CONTENT_DIR)
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
    .filter((slug) => slug !== 'site')
    .sort();
  const rowSlugs = rows.map(({ slug }) => slug).sort();
  const converterSlugs = [
    ...readFileSync(CONVERTER_PATH, 'utf8').matchAll(
      /source:\s*['"]\.specify\/content\/([^'"]+)\.json['"]/g,
    ),
  ]
    .map((match) => match[1])
    .filter((slug): slug is string => slug !== undefined)
    .filter((slug) => !slug.includes('/'))
    .filter((slug) => slug !== 'site')
    .sort();

  expect(rowSlugs).toStrictEqual(contentSlugs);
  expect(converterSlugs).toStrictEqual(contentSlugs);
  expect([...PROJECT_SLUGS].sort()).toStrictEqual(contentSlugs);
});

test('relationship completeness: content files, fidelity rows and converter entries agree', () => {
  const contentSlugs = readdirSync(RELATIONSHIPS_DIR)
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
    .sort();
  const rowSlugs = relationshipRows.map(({ slug }) => slug).sort();
  const sourceSlugs = Object.keys(RELATIONSHIP_SOURCES).sort();
  const converterSlugs = [
    ...readFileSync(CONVERTER_PATH, 'utf8').matchAll(
      /source:\s*['"]\.specify\/content\/relationships\/([^'"]+)\.json['"]/g,
    ),
  ]
    .map((match) => match[1])
    .filter((slug): slug is string => slug !== undefined)
    .sort();

  expect(rowSlugs).toStrictEqual(contentSlugs);
  expect(sourceSlugs).toStrictEqual(contentSlugs);
  expect(converterSlugs).toStrictEqual(contentSlugs);

  for (const slug of contentSlugs) {
    expect(PROJECT_SLUGS).toContain(slug);
  }
});
