import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { parseProject } from 'xploder';
import { describe, expect, test } from 'vitest';

import { PROJECT_SLUGS } from '../content/projects';
import { SITE_REGISTRY } from '../content/tech-registry';
import { jevToolkit } from '../content/projects/jev-toolkit';
import { jevToolkitSource } from '../content/projects/jev-toolkit.source';
import { websocketInspector } from '../content/projects/websocket-inspector';
import { websocketInspectorSource } from '../content/projects/websocket-inspector.source';

const APP_WEB_ROOT = fileURLToPath(new URL('..', import.meta.url));
const CONTENT_DIR = fileURLToPath(new URL('../../../.specify/content', import.meta.url));
const CONVERTER_PATH = fileURLToPath(new URL('../scripts/convert-content.ts', import.meta.url));

const rows = [
  {
    slug: 'websocket-inspector',
    jsonPath: fileURLToPath(
      new URL('../../../.specify/content/websocket-inspector.json', import.meta.url),
    ),
    source: websocketInspectorSource,
    project: websocketInspector,
    sourcePath: fileURLToPath(
      new URL('../content/projects/websocket-inspector.source.ts', import.meta.url),
    ),
  },
  {
    slug: 'jev-toolkit',
    jsonPath: fileURLToPath(new URL('../../../.specify/content/jev-toolkit.json', import.meta.url)),
    source: jevToolkitSource,
    project: jevToolkit,
    sourcePath: fileURLToPath(
      new URL('../content/projects/jev-toolkit.source.ts', import.meta.url),
    ),
  },
] as const;

describe.each(rows)('$slug content fidelity', ({ slug, jsonPath, source, project, sourcePath }) => {
  const bytes = readFileSync(jsonPath);
  const json: unknown = JSON.parse(bytes.toString('utf8'));

  test('(a) generated module is strictly equal to the canonical JSON', () => {
    expect(source).toStrictEqual(json);
  });

  test('(b) parsed module is strictly equal to the canonical JSON parsed project', () => {
    expect(project).toStrictEqual(parseProject(json, { registry: SITE_REGISTRY }));
  });

  test('(c) content:convert --check exits 0', () => {
    const result = spawnSync(process.execPath, [CONVERTER_PATH, '--check'], {
      cwd: APP_WEB_ROOT,
      encoding: 'utf8',
    });

    expect(result.status, result.stderr || result.stdout).toBe(0);
  });

  test('(d) generated header records the canonical JSON sha256', () => {
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const expectedHeader = `/* Generated by apps/web/scripts/convert-content.ts from .specify/content/${slug}.json (sha256 ${sha256}). Do not edit; run pnpm --filter web content:convert. */`;
    const firstLine = readFileSync(sourcePath, 'utf8').split('\n', 1)[0];

    expect(firstLine).toBe(expectedHeader);
  });

  test('(e) negative control: a mutated canonical copy is not strictly equal', () => {
    const mutated = structuredClone(json) as { meta: { tagline: string } };
    mutated.meta.tagline = `${mutated.meta.tagline} (mutated)`;

    expect(source).not.toStrictEqual(mutated);
  });

  test('(e2) negative control: a mutated nested copy is not strictly equal', () => {
    const mutated = structuredClone(json) as {
      layers: Array<{ components: Array<{ summary: string }> }>;
    };
    mutated.layers[4]!.components[2]!.summary = `${mutated.layers[4]!.components[2]!.summary} (mutated)`;

    expect(source).not.toStrictEqual(mutated);
  });
});

test('completeness: content files, fidelity rows and converter entries agree', () => {
  const contentSlugs = readdirSync(CONTENT_DIR)
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
    .filter((slug) => slug !== 'site')
    .sort();
  const rowSlugs = rows.map(({ slug }) => slug).sort();
  const converterSlugs = [
    ...readFileSync(CONVERTER_PATH, 'utf8').matchAll(
      /source:\s*['"]\.specify\/content\/([^'"]+)\.json['"]/g,
    ),
  ]
    .map((match) => match[1])
    .filter((slug): slug is string => slug !== undefined)
    .filter((slug) => slug !== 'site')
    .sort();

  expect(rowSlugs).toStrictEqual(contentSlugs);
  expect(converterSlugs).toStrictEqual(contentSlugs);
  expect([...PROJECT_SLUGS].sort()).toStrictEqual(contentSlugs);
});
