import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, expect, test } from 'vitest';

import { siteSource } from '../content/site.source';

const APP_WEB_ROOT = fileURLToPath(new URL('..', import.meta.url));
const JSON_PATH = fileURLToPath(new URL('../../../.specify/content/site.json', import.meta.url));
const SOURCE_PATH = fileURLToPath(new URL('../content/site.source.ts', import.meta.url));
const CONVERTER_PATH = fileURLToPath(new URL('../scripts/convert-content.ts', import.meta.url));

describe('site copy fidelity', () => {
  const bytes = readFileSync(JSON_PATH);
  const json: unknown = JSON.parse(bytes.toString('utf8'));

  test('(a) generated module is strictly equal to the canonical JSON', () => {
    expect(siteSource).toStrictEqual(json);
  });

  test('(b) content:convert --check exits 0', () => {
    const result = spawnSync(process.execPath, [CONVERTER_PATH, '--check'], {
      cwd: APP_WEB_ROOT,
      encoding: 'utf8',
    });

    expect(result.status, result.stderr || result.stdout).toBe(0);
  });

  test('(c) generated header records the canonical JSON sha256', () => {
    const sha256 = createHash('sha256').update(bytes).digest('hex');
    const expectedHeader = `/* Generated by apps/web/scripts/convert-content.ts from .specify/content/site.json (sha256 ${sha256}). Do not edit; run pnpm --filter web content:convert. */`;
    const firstLine = readFileSync(SOURCE_PATH, 'utf8').split('\n', 1)[0];

    expect(firstLine).toBe(expectedHeader);
  });

  test('(d) negative control: a mutated canonical copy is not strictly equal', () => {
    const mutated = structuredClone(json) as { meta: { title: string } };
    mutated.meta.title = `${mutated.meta.title} (mutated)`;

    expect(siteSource).not.toStrictEqual(mutated);
  });
});
