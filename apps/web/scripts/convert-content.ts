import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import prettier from 'prettier';

const APP_WEB_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO_ROOT = resolve(APP_WEB_ROOT, '../..');

interface ContentTypeImport {
  readonly typeName: string;
  readonly moduleSpecifier: string;
}

interface ContentFile {
  readonly source: string;
  readonly target: string;
  readonly exportName: string;
  readonly typeImport: ContentTypeImport;
}

const CONTENT_FILES: readonly ContentFile[] = [
  {
    source: '.specify/content/websocket-inspector.json',
    target: 'content/projects/websocket-inspector.source.ts',
    exportName: 'websocketInspectorSource',
    typeImport: { typeName: 'ProjectInput', moduleSpecifier: 'xploder' },
  },
  {
    source: '.specify/content/jev-toolkit.json',
    target: 'content/projects/jev-toolkit.source.ts',
    exportName: 'jevToolkitSource',
    typeImport: { typeName: 'ProjectInput', moduleSpecifier: 'xploder' },
  },
  {
    source: '.specify/content/site.json',
    target: 'content/site.source.ts',
    exportName: 'siteSource',
    typeImport: { typeName: 'SiteCopy', moduleSpecifier: './site-copy' },
  },
];

const args = process.argv.slice(2);
const check = args.length === 1 && args[0] === '--check';

if (args.length > 0 && !check) {
  console.error('Usage: node apps/web/scripts/convert-content.ts [--check]');
  process.exitCode = 2;
} else {
  for (const entry of CONTENT_FILES) {
    const sourcePath = resolve(REPO_ROOT, entry.source);
    const targetPath = resolve(APP_WEB_ROOT, entry.target);
    const sourceBytes = readFileSync(sourcePath);
    const sha256 = createHash('sha256').update(sourceBytes).digest('hex');
    const content: unknown = JSON.parse(sourceBytes.toString('utf8'));
    const text = `/* Generated by apps/web/scripts/convert-content.ts from ${entry.source} (sha256 ${sha256}). Do not edit; run pnpm --filter web content:convert. */
import type { ${entry.typeImport.typeName} } from '${entry.typeImport.moduleSpecifier}';

export const ${entry.exportName} = ${JSON.stringify(content, null, 2)} satisfies ${entry.typeImport.typeName};
`;
    const prettierConfig = (await prettier.resolveConfig(targetPath)) ?? {};
    const formatted = await prettier.format(text, {
      ...prettierConfig,
      filepath: targetPath,
    });
    const targetLabel = relative(REPO_ROOT, targetPath);

    if (check) {
      const current = existsSync(targetPath) ? readFileSync(targetPath) : Buffer.alloc(0);

      if (current.equals(Buffer.from(formatted))) {
        console.log(`content:convert: ${targetLabel} is up to date`);
      } else {
        console.error(`content:convert: generated content is stale: ${targetLabel}`);
        console.error(firstDifferingLine(current.toString('utf8'), formatted));
        process.exitCode = 1;
      }
    } else {
      writeFileSync(targetPath, formatted);
      console.log(`content:convert: wrote ${targetLabel}`);
    }
  }
}

function firstDifferingLine(actual: string, expected: string): string {
  const actualLines = actual.split('\n');
  const expectedLines = expected.split('\n');
  const lineCount = Math.max(actualLines.length, expectedLines.length);

  for (let index = 0; index < lineCount; index += 1) {
    const actualLine = actualLines[index];
    const expectedLine = expectedLines[index];

    if (actualLine !== expectedLine) {
      return `line ${index + 1}\n  actual:   ${actualLine ?? '<missing>'}\n  expected: ${expectedLine ?? '<missing>'}`;
    }
  }

  return 'the generated content differs only in line endings';
}
