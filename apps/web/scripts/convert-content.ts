import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import prettier from 'prettier';

const APP_WEB_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const REPO_ROOT = resolve(APP_WEB_ROOT, '../..');
const SOURCE_PATH = resolve(REPO_ROOT, '.specify/content/websocket-inspector.json');
const TARGET_PATH = resolve(APP_WEB_ROOT, 'content/projects/websocket-inspector.source.ts');
const SOURCE_LABEL = '.specify/content/websocket-inspector.json';
const HEADER_PREFIX = `Generated by apps/web/scripts/convert-content.ts from ${SOURCE_LABEL}`;

const args = process.argv.slice(2);
const check = args.length === 1 && args[0] === '--check';

if (args.length > 0 && !check) {
  console.error('Usage: node apps/web/scripts/convert-content.ts [--check]');
  process.exitCode = 2;
} else {
  const sourceBytes = readFileSync(SOURCE_PATH);
  const sha256 = createHash('sha256').update(sourceBytes).digest('hex');
  const content: unknown = JSON.parse(sourceBytes.toString('utf8'));
  const text = `/* ${HEADER_PREFIX} (sha256 ${sha256}). Do not edit; run pnpm --filter web content:convert. */
import type { ProjectInput } from 'xploder';

export const websocketInspectorSource = ${JSON.stringify(content, null, 2)} satisfies ProjectInput;
`;
  const prettierConfig = (await prettier.resolveConfig(TARGET_PATH)) ?? {};
  const formatted = await prettier.format(text, {
    ...prettierConfig,
    filepath: TARGET_PATH,
  });

  if (check) {
    const current = existsSync(TARGET_PATH) ? readFileSync(TARGET_PATH) : Buffer.alloc(0);

    if (current.equals(Buffer.from(formatted))) {
      console.log('content:convert: generated content is up to date');
    } else {
      console.error(
        `content:convert: generated content is stale: ${relative(REPO_ROOT, TARGET_PATH)}`,
      );
      console.error(firstDifferingLine(current.toString('utf8'), formatted));
      process.exitCode = 1;
    }
  } else {
    writeFileSync(TARGET_PATH, formatted);
    console.log(`content:convert: wrote ${relative(REPO_ROOT, TARGET_PATH)}`);
  }
}

function firstDifferingLine(actual: string, expected: string): string {
  const actualLines = actual.split('\n');
  const expectedLines = expected.split('\n');
  const lineCount = Math.max(actualLines.length, expectedLines.length);

  for (let index = 0; index < lineCount; index += 1) {
    const actualLine = actualLines[index];
    const expectedLine = expectedLines[index];

    if (actualLine !== expectedLine) {
      return `line ${index + 1}\n  actual:   ${actualLine ?? '<missing>'}\n  expected: ${expectedLine ?? '<missing>'}`;
    }
  }

  return 'the generated content differs only in line endings';
}
